// Builds the draft n8n workflow for the literature engine.
// The Code node embeds the tested lit/ modules as one bundle, so production runs the same code the tests run.
// Usage: node lit/n8n/build.js   -> writes lit/n8n/workflow.json
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const MODULES = ['lit/format', 'lit/filter', 'lit/validate', 'lit/synthesis', 'lit/pipeline',
  'lit/sources/grey', 'lit/sources/openalex', 'lit/sources/crossref', 'lit/sources/unpaywall', 'lit/sources/europepmc', 'lit/sources/core', 'lit/sources/doaj',
  'write/formats', 'write/templates', 'write/plan'];

function bundle() {
  const parts = ['// ---- bundled modules (generated by lit/n8n/build.js; do not edit here) ----',
    'const __reg = {};',
    'const __req = (p) => __reg[p.split("/").pop().replace(/\\.js$/, "")];'];
  for (const m of MODULES) {
    const src = fs.readFileSync(path.join(ROOT, m + '.js'), 'utf8');
    const name = path.basename(m);
    parts.push(`__reg[${JSON.stringify(name)}] = (function () { const module = { exports: {} }; const exports = module.exports; const require = __req;\n${src}\nreturn module.exports; })();`);
  }
  return parts.join('\n');
}

// Minimal URLSearchParams for sandboxes that do not provide it (only used to build query strings).
const SHIM = `
if (typeof URLSearchParams === 'undefined') {
  globalThis.URLSearchParams = class { constructor(o) { this.o = Object.assign({}, o || {}); }
    toString() { return Object.keys(this.o).map(k => encodeURIComponent(k) + '=' + encodeURIComponent(this.o[k])).join('&'); } };
}
`;

const FINISH = `
const { finishLiterature } = __req('pipeline');
const prep = $('Literature engine').first().json || {};
const out = $input.first().json || {};
let text = '', error = '';
if (!prep.early) {
  if (out.error) error = String(out.error.message || JSON.stringify(out.error)).slice(0, 300);
  else text = ((out.candidates && out.candidates[0] && out.candidates[0].content && out.candidates[0].content.parts) || []).map(p => p.text || '').join('');
  // A reply cut off at the length limit would shorten the section, so it is not used.
  if (!error && out.candidates && out.candidates[0] && out.candidates[0].finishReason === 'MAX_TOKENS') error = 'The writer reply was cut off at its length limit, so the section was not changed.';
}
const result = finishLiterature({ prep, text, error });
return [{ json: Object.assign({}, result, { searched: prep.searched, sourceErrors: prep.sourceErrors }) }];
`;

const RUNNER = `
// ---- runner ----
const OA = __req('openalex'), EPMC = __req('europepmc'), DOAJ = __req('doaj'), CORE = __req('core'), GREY = __req('grey');
const { prepareLiterature, finishLiterature } = __req('pipeline');
const MAILTO = ''; // env vars are blocked in Code nodes on this n8n server

// The engine's input is the auth checker's output, so read the form from the webhook node.
const hook = $("Literature webhook").first().json || {};
const b = hook.body || hook;
const question = String(b.question || '').trim();
let queries = [], f = {};
try { queries = JSON.parse(b.queries || '[]'); f = JSON.parse(b.filters || '{}'); } catch (e) { return [{ json: { early: { ok: false, reason: 'Malformed queries or filters' } } }]; }
const auth = $("Call 'Q1 Auth - Check Key'").first().json || {};
if (auth.authorized !== true)
  return [{ json: { early: { ok: false, reason: 'Not authorised' } } }];
if (!question || !queries.length)
  return [{ json: { early: { ok: false, reason: 'A research question and at least one search query are required' } } }];

// Optional user settings from the form: expected length text and a list of headings or points.
function cleanLength(v) { return String(v || '').replace(/[^0-9A-Za-z ,.\u2013-]/g, '').trim().slice(0, 60); }
function cleanOutline(v) {
  let list = [];
  try { list = JSON.parse(v || '[]'); } catch (e) { list = []; }
  return (Array.isArray(list) ? list : []).map(x => String(x).trim().slice(0, 120)).filter(Boolean).slice(0, 12);
}

const includeGrey = f.includeGrey !== false;
const yearFrom = f.yearFrom || null;
// n8n Code nodes expose the HTTP helper as this.helpers (not $helpers) and may lack URLSearchParams.
const HTTP = (typeof $helpers !== 'undefined' && $helpers) || (this && this.helpers);
const fetchJson = async (url, opts = {}) => HTTP.httpRequest({ method: 'GET', url, headers: opts.headers || {}, json: true });

const records = [], errors = [];
const run = async (name, fn) => { try { records.push(...(await fn())); } catch (e) { errors.push(name + ': ' + e.message); } };
for (const q of queries.slice(0, 8)) {
  await run('openalex', () => OA.searchOpenAlex(q, { yearFrom, perPage: 25, mailto: MAILTO }, fetchJson));
  await run('europepmc', () => EPMC.search(q, { yearFrom, pageSize: 25 }, fetchJson));
  await run('doaj', () => DOAJ.search(q, { yearFrom, pageSize: 25 }, fetchJson));
  if (includeGrey) await run('grey', () => GREY.search(q, { yearFrom, perPage: 25, mailto: MAILTO }, fetchJson));
}

const types = includeGrey ? ['article', 'review', 'conference', 'grey'] : ['article', 'review', 'conference'];
const prep = prepareLiterature({
  question, records, style: b.style || '',
  length: cleanLength(b.length), outline: cleanOutline(b.outline),
  filters: { types, yearFrom, minCitations: f.minCitations == null ? null : f.minCitations, dropRetracted: true, dedupe: true }
});
if (auth.authorized !== true) prep.early = { ok: false, reason: 'Not authorised' };
return [{ json: Object.assign({}, prep, { searched: records.length, sourceErrors: errors }) }];
// The next node (Gemini) sends prep.prompt; the finish node reads this output back by name.
`;

function workflow() {
  const code = SHIM + bundle() + '\n' + RUNNER;
  return {
    name: 'Q1 Literature Review (draft)',
    nodes: [
      { parameters: { httpMethod: 'POST', path: 'q1-literature-run', responseMode: 'responseNode', options: {} },
        id: 'lit-webhook', name: 'Literature webhook', type: 'n8n-nodes-base.webhook', typeVersion: 2, position: [0, 200], webhookId: 'q1-literature-run' },
      { parameters: { jsCode: code },
        id: 'lit-engine', name: 'Literature engine', type: 'n8n-nodes-base.code', typeVersion: 2, position: [260, 200] },
      // Gemini free tier. Uses the existing Google Gemini (PaLM) API credential, chosen in the node.
      // Model: gemini-3.5-flash-lite (on the Gemini API free tier).
      { parameters: {
          method: 'POST', url: 'https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash-lite:generateContent',
          authentication: 'predefinedCredentialType', nodeCredentialType: 'googlePalmApi',
          sendBody: true, specifyBody: 'json',
          jsonBody: "={{ { contents: [{ parts: [{ text: $json.prompt || '' }] }], generationConfig: { maxOutputTokens: 32000, temperature: 0.2 } } }}",
          options: {} },
        id: 'lit-gemini', name: 'Gemini draft', type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position: [500, 200], continueOnFail: true },
      { parameters: { jsCode: SHIM + bundle() + '\n' + FINISH },
        id: 'lit-finish', name: 'Literature finish', type: 'n8n-nodes-base.code', typeVersion: 2, position: [740, 200] },
      { parameters: { respondWith: 'json', responseBody: '={{ $json }}', options: {} },
        id: 'lit-respond', name: 'Respond', type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1.1, position: [980, 200] }
    ],
    connections: {
      'Literature webhook': { main: [[{ node: 'Literature engine', type: 'main', index: 0 }]] },
      'Literature engine': { main: [[{ node: 'Gemini draft', type: 'main', index: 0 }]] },
      'Gemini draft': { main: [[{ node: 'Literature finish', type: 'main', index: 0 }]] },
      'Literature finish': { main: [[{ node: 'Respond', type: 'main', index: 0 }]] }
    },
    settings: { executionOrder: 'v1' },
    active: false
  };
}

// ---- section writer (Writing from scratch): its own workflow, same bundled code ----
const WRITE_RUNNER = `
// Writes one section of a "Writing from scratch" document, or revises one paragraph (action: revise).
const hook = $("Write webhook").first().json || {};
const b = hook.body || hook;
const auth = $("Call 'Q1 Auth - Check Key'").first().json || {};
if (auth.authorized !== true)
  return [{ json: { early: { ok: false, reason: 'Not authorised' } } }];

const T = __req('templates'), P = __req('plan'), F = __req('filter'), FMT = __req('format'), SYN = __req('synthesis');
const OA = __req('openalex'), EPMC = __req('europepmc'), DOAJ = __req('doaj'), GREY = __req('grey');
const MAILTO = '';
const type = String(b.type || '');
const section = String(b.section || '');
const sec = T.REPORT_TYPES[type] && T.REPORT_TYPES[type].sections.find(x => x.id === section);
if (!sec) return [{ json: { early: { ok: false, reason: 'Unknown report type or section' } } }];

let project = {}, prior = [];
try { project = JSON.parse(b.project || '{}'); prior = JSON.parse(b.prior || '[]'); }
catch (e) { return [{ json: { early: { ok: false, reason: 'Malformed project or earlier sections' } } }]; }
prior = (Array.isArray(prior) ? prior : []).slice(0, 8).map(x => ({ title: String(x.title || '').slice(0, 120), text: String(x.text || '').slice(0, 8000) }));
const words = Math.max(0, Math.round(Number(b.words) || 0));
const points = String(b.points || '').slice(0, 4000);
const hint = String(b.hint || '').slice(0, 1000);
const revise = b.action === 'revise';
const para = b.action === 'paragraph';
// Transform: rewrite a section of an uploaded article into the target format, with the sources the user picked.
const transform = b.action === 'transform';
// One paragraph for a set of sources (action: addset): the writer returns only that paragraph, and the app adds it to the section.
const setPara = b.action === 'addset';
// Relevance check: the writer judges each found work against this section (action: verify). No text is written.
if (b.action === 'verify') {
  let items = [];
  try { items = JSON.parse(b.items || '[]'); } catch (e) { return [{ json: { early: { ok: false, reason: 'The works to check could not be read' } } }]; }
  items = (Array.isArray(items) ? items : []).slice(0, 40).map(w => ({ key: String(w.key || ''), title: String(w.title || '').slice(0, 300), abstract: String(w.abstract || '').slice(0, 600) })).filter(w => w.key);
  if (!items.length) return [{ json: { early: { ok: false, reason: 'No works to check' } } }];
  const kwList = String(b.keywords || '').slice(0, 500);
  const lines = [
    'You check whether academic works are relevant to one section of a document.',
    'Document: ' + (project.title || '(not given)'),
    'Section: ' + sec.title + '. Purpose: ' + (sec.brief || ''),
    'Keywords for this section: ' + (kwList || '(none)'),
    'For each numbered work, decide whether it directly addresses this section topic and could support writing it. A shared word alone (a place name, a generic term) is not enough.',
    'Reply with only a JSON array, one object per work, in the same order: {"n": number, "relevant": true or false, "reason": "a short reason, under 15 words"}.',
    'Works:'
  ];
  items.forEach((w, i) => lines.push((i + 1) + '. ' + w.title + (w.abstract ? ' | ' + w.abstract : '')));
  return [{ json: { prompt: lines.join('\\n'), verify: true, verifyKeys: items.map(w => w.key), early: null, words: 0, kept: [], searched: 0, sourceErrors: [] } }];
}
let works = [];
if (transform || setPara) {
  try { works = JSON.parse(b.works || '[]'); } catch (e) { return [{ json: { early: { ok: false, reason: 'The selected literature could not be read' } } }]; }
  if (transform && !String(b.source || '').trim()) return [{ json: { early: { ok: false, reason: 'Paste or upload the article to transform first' } } }];
}
const point = String(b.point || '').slice(0, 1000);
if (para && !point.trim())
  return [{ json: { early: { ok: false, reason: 'The outline point for this paragraph is missing' } } }];
const paragraph = String(b.paragraph || '').slice(0, 6000);
if (revise) {
  if (!paragraph.trim()) return [{ json: { early: { ok: false, reason: 'Choose a paragraph to revise' } } }];
  if (!P.REVISE_MODES[b.mode]) return [{ json: { early: { ok: false, reason: 'Choose how to revise: connect, discuss or cite' } } }];
  if (!P.MODIFICATIONS[b.modification]) return [{ json: { early: { ok: false, reason: 'Choose a modification type first' } } }];
  if (b.mode === 'discuss' && !String(b.instruction || '').trim()) return [{ json: { early: { ok: false, reason: 'Write the instruction for the AI first' } } }];
} else if (!para && !transform && !setPara && !points.trim()) {
  return [{ json: { early: { ok: false, reason: 'Add the content points for this section first' } } }];
}

// n8n Code nodes expose the HTTP helper as this.helpers (not $helpers) and may lack URLSearchParams.
const HTTP = (typeof $helpers !== 'undefined' && $helpers) || (this && this.helpers);
const fetchJson = async (url, opts = {}) => HTTP.httpRequest({ method: 'GET', url, headers: opts.headers || {}, json: true });
const records = [], errors = [];
const run = async (name, fn) => { try { records.push(...(await fn())); } catch (e) { errors.push(name + ': ' + e.message); } };

// Body sections are sourced from the literature search; abstracts, titles and references are not.
const queries = revise
  ? [project.question, project.topic, hint, paragraph.slice(0, 200)].map(x => String(x || '').trim()).filter(Boolean).slice(0, 4)
  : para
    ? [project.question, project.topic, hint, point].map(x => String(x || '').trim()).filter(Boolean).slice(0, 4)
    : [project.question, project.topic, hint].concat(points.split('\\n')).map(x => String(x || '').trim()).filter(Boolean).slice(0, 4);
if (!transform && (revise ? b.mode === 'cite' : (para || sec.fixed == null))) {
  for (const q of queries) {
    await run('openalex', () => OA.searchOpenAlex(q, { yearFrom: null, perPage: 25, mailto: MAILTO }, fetchJson));
    await run('europepmc', () => EPMC.search(q, { yearFrom: null, pageSize: 25 }, fetchJson));
    await run('doaj', () => DOAJ.search(q, { yearFrom: null, pageSize: 25 }, fetchJson));
    await run('grey', () => GREY.search(q, { yearFrom: null, perPage: 25, mailto: MAILTO }, fetchJson));
  }
}
if (transform || setPara) for (const w of works.slice(0, 60)) { try { records.push(OA.normalizeWork(w)); } catch (e) { errors.push('work: ' + e.message); } }
// Sources the user picked are not dropped for a missing method statement; they are the user's choice.
const filt = F.filterSources(records, { types: ['article', 'review', 'conference', 'grey'], yearFrom: null, minCitations: null, dropRetracted: true, dedupe: true, greyNeedsMethod: !(transform || setPara) });
const kept = filt.kept || [];
const style = FMT.resolveStyle(b.style || '');
const sourcesText = kept.length ? SYN.sourceList(kept) : '';
// Set paragraphs use short labels (S1, S2 ...) in the prompt, in the order the app sent the sources; the app maps them back to its own keys.
const setSourcesText = setPara ? works.slice(0, 10).map((w, i) => {
  let r = null; try { r = OA.normalizeWork(w); } catch (e) { r = null; }
  const who = r && r.authors && r.authors[0] ? r.authors[0].family : 'Unknown author';
  return 'S' + (i + 1) + ': ' + who + ' (' + ((r && r.year) || 'n.d.') + '). ' + ((r && r.title) || w.title || '');
}).join('\\n') : '';
const priorParas = para ? String(b.priorParagraphs || '').split('\\n\\n').map(x => x.trim()).filter(Boolean).slice(-6) : [];
const prompt = setPara
  ? P.buildSetParagraphPrompt({ section, sourcesText: setSourcesText, existing: String(b.existing || ''), outline: String(b.outline || ''), instruction: String(b.instruction || ''), project })
  : transform
  ? P.buildTransformPrompt({ type, section, words, source: String(b.source || ''), prior, sourcesText, project, existing: String(b.existing || '').slice(0, 60000), instruction: String(b.instruction || '').slice(0, 1000), approach: String(b.approach || '').slice(0, 40), style: String(b.style || '').slice(0, 20) })
  : para
  ? P.buildParagraphPrompt({ type, section, point, words, prior: priorParas, hint, sourcesText, style: String(b.style || ''), project, position: Number(b.position) || 1, total: Number(b.total) || 1 })
  : revise
  ? P.buildRevisePrompt({ type, section, paragraph, previous: String(b.previous || '').slice(0, 6000), mode: b.mode, modification: b.modification, instruction: String(b.instruction || '').slice(0, 1000), sourcesText, style: String(b.style || ''), project })
  : P.buildSectionPrompt({ type, section, words, points, project, prior, sourcesText, hint });
const budget = transform ? words : revise ? P.countWords(paragraph) : words;
const prep = { early: null, kept, style, log: filt.log, excluded: filt.excluded, prompt, words: budget, searched: records.length, sourceErrors: errors };
return [{ json: prep }];
// The Gemini node sends prep.prompt; the finish node reads this output back by name.
`;

const WRITE_FINISH = `
const { finishLiterature } = __req('pipeline');
const prep = $('Write engine').first().json || {};
const out = $input.first().json || {};
let text = '', error = '';
if (prep.verify) {
  if (prep.early) return [{ json: { ok: false, reason: prep.early.reason, verdicts: [] } }];
  if (out.error) return [{ json: { ok: false, reason: 'The relevance check failed: ' + String(out.error.message || 'no reason given').slice(0, 200), verdicts: [] } }];
  const raw = ((out.candidates && out.candidates[0] && out.candidates[0].content && out.candidates[0].content.parts) || []).map(p => p.text || '').join('');
  const start = raw.indexOf('['), end = raw.lastIndexOf(']');
  let arr = [];
  try { arr = JSON.parse(start >= 0 && end > start ? raw.slice(start, end + 1) : '[]'); } catch (e) { arr = []; }
  const keys = prep.verifyKeys || [];
  const verdicts = (Array.isArray(arr) ? arr : []).map(v => ({ key: keys[(Number(v.n) || 0) - 1], relevant: v.relevant === true, reason: String(v.reason || '').slice(0, 160) })).filter(v => v.key);
  if (!verdicts.length) return [{ json: { ok: false, reason: 'The relevance check gave no readable answer.', verdicts: [] } }];
  return [{ json: { ok: true, verdicts } }];
}
if (!prep.early) {
  if (out.error) error = String(out.error.message || JSON.stringify(out.error)).slice(0, 300);
  else text = ((out.candidates && out.candidates[0] && out.candidates[0].content && out.candidates[0].content.parts) || []).map(p => p.text || '').join('');
  // A reply cut off at the length limit would shorten the section, so it is not used.
  if (!error && out.candidates && out.candidates[0] && out.candidates[0].finishReason === 'MAX_TOKENS') error = 'The writer reply was cut off at its length limit, so the section was not changed.';
}
const result = finishLiterature({ prep, text, error });
const draft = result.draft || '';
const ok = !!draft && !error && !prep.early;
const reason = prep.early ? prep.early.reason : (ok ? undefined : (result.reason || error || 'No text was written.'));
return [{ json: { ok, text: draft, reason, warning: ok ? result.reason : undefined, labels: result.labels || {}, references: result.references || [], unresolvedKeys: result.unresolvedKeys || [], words: draft ? draft.trim().split(/\\s+/).length : 0, budget: prep.words || 0, sources: prep.kept ? prep.kept.length : 0 } }];
`;

