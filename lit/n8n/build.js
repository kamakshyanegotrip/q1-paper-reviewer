// Builds the draft n8n workflow for the literature engine.
// The Code node embeds the tested lit/ modules as one bundle, so production runs the same code the tests run.
// Usage: node lit/n8n/build.js   -> writes lit/n8n/workflow.json
'use strict';
const fs = require('fs');
const path = require('path');

const LIT = path.join(__dirname, '..');
const MODULES = ['format', 'filter', 'validate', 'synthesis', 'pipeline',
  'sources/grey', 'sources/openalex', 'sources/crossref', 'sources/unpaywall', 'sources/europepmc', 'sources/core', 'sources/doaj'];

function bundle() {
  const parts = ['// ---- bundled lit/ modules (generated by lit/n8n/build.js; do not edit here) ----',
    'const __reg = {};',
    'const __req = (p) => __reg[p.split("/").pop().replace(/\\.js$/, "")];'];
  for (const m of MODULES) {
    const src = fs.readFileSync(path.join(LIT, m + '.js'), 'utf8');
    const name = path.basename(m);
    parts.push(`__reg[${JSON.stringify(name)}] = (function () { const module = { exports: {} }; const exports = module.exports; const require = __req;\n${src}\nreturn module.exports; })();`);
  }
  return parts.join('\n');
}

const RUNNER = `
// ---- runner ----
const OA = __req('openalex'), EPMC = __req('europepmc'), DOAJ = __req('doaj'), CORE = __req('core'), GREY = __req('grey');
const { runLiteratureReview } = __req('pipeline');
const MODEL = 'claude-sonnet-5-5';
const MAILTO = $env.LIT_CONTACT_EMAIL || '';

const b = ($input.first().json.body) || $input.first().json;
const question = String(b.question || '').trim();
let queries = [], f = {};
try { queries = JSON.parse(b.queries || '[]'); f = JSON.parse(b.filters || '{}'); } catch (e) { return [{ json: { ok: false, reason: 'Malformed queries or filters' } }]; }
const auth = $("Call 'Q1 Auth - Check Key'").first().json || {};
if (auth.authorized !== true)
  return [{ json: { ok: false, reason: 'Not authorised' } }];
if (!question || !queries.length)
  return [{ json: { ok: false, reason: 'A research question and at least one search query are required' } }];

const includeGrey = f.includeGrey !== false;
const yearFrom = f.yearFrom || null;
const fetchJson = async (url, opts = {}) => $helpers.httpRequest({ method: 'GET', url, headers: opts.headers || {}, json: true });

const records = [], errors = [];
const run = async (name, fn) => { try { records.push(...(await fn())); } catch (e) { errors.push(name + ': ' + e.message); } };
for (const q of queries.slice(0, 8)) {
  await run('openalex', () => OA.searchOpenAlex(q, { yearFrom, perPage: 25, mailto: MAILTO }, fetchJson));
  await run('europepmc', () => EPMC.search(q, { yearFrom, pageSize: 25 }, fetchJson));
  await run('doaj', () => DOAJ.search(q, { yearFrom, pageSize: 25 }, fetchJson));
  if ($env.CORE_API_KEY) await run('core', () => CORE.search(q, { apiKey: $env.CORE_API_KEY, yearFrom, pageSize: 25 }, fetchJson));
  if (includeGrey) await run('grey', () => GREY.search(q, { yearFrom, perPage: 25, mailto: MAILTO }, fetchJson));
}

const llm = async (prompt) => {
  const r = await $helpers.httpRequest({
    method: 'POST', url: 'https://api.anthropic.com/v1/messages', json: true,
    headers: { 'x-api-key': $env.ANTHROPIC_API_KEY, 'anthropic-version': '2023-06-01', 'content-type': 'application/json' },
    body: { model: MODEL, max_tokens: 3000, messages: [{ role: 'user', content: prompt }] }
  });
  return (r.content || []).map(c => c.text || '').join('');
};

const types = includeGrey ? ['article', 'review', 'conference', 'grey'] : ['article', 'review', 'conference'];
const result = await runLiteratureReview({
  question, records, style: b.style || '', llm, maxAttempts: 3,
  filters: { types, yearFrom, minCitations: f.minCitations == null ? null : f.minCitations, dropRetracted: true, dedupe: true }
});
return [{ json: Object.assign({}, result, { searched: records.length, sourceErrors: errors }) }];
`;

function workflow() {
  const code = bundle() + '\n' + RUNNER;
  return {
    name: 'Q1 Literature Review (draft)',
    nodes: [
      { parameters: { httpMethod: 'POST', path: 'q1-literature-run', responseMode: 'responseNode', options: {} },
        id: 'lit-webhook', name: 'Literature webhook', type: 'n8n-nodes-base.webhook', typeVersion: 2, position: [0, 200], webhookId: 'q1-literature-run' },
      { parameters: { jsCode: code },
        id: 'lit-engine', name: 'Literature engine', type: 'n8n-nodes-base.code', typeVersion: 2, position: [260, 200] },
      { parameters: { respondWith: 'json', responseBody: '={{ $json }}', options: {} },
        id: 'lit-respond', name: 'Respond', type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1.1, position: [520, 200] }
    ],
    connections: {
      'Literature webhook': { main: [[{ node: 'Literature engine', type: 'main', index: 0 }]] },
      'Literature engine': { main: [[{ node: 'Respond', type: 'main', index: 0 }]] }
    },
    settings: { executionOrder: 'v1' },
    active: false
  };
}

if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, 'workflow.json'), JSON.stringify(workflow(), null, 2));
  console.log('wrote lit/n8n/workflow.json');
}
module.exports = { workflow, bundle, RUNNER };
